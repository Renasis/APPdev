class ProductModel {

  final String id;
  final String name;
  final String category;
  final String brand;
  final double price;
  final String image;
  final int stock;
  final String description;


  const ProductModel({

    required this.id,
    required this.name,
    required this.category,
    required this.brand,
    required this.price,
    required this.image,
    required this.stock,
    required this.description,

  });

}